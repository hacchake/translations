def chapter(n):
    fs = sorted(p for p in (D / "draft").glob(f"c{n:02d}*.md")
                if re.fullmatch(rf"c{n:02d}[a-z]?", p.stem))
    assert fs, n
    return "\n\n".join(f.read_text(encoding="utf-8").strip() for f in fs)


def part_body(no, title, a, b):
    head = f"## 第{no}部　{title}"
    if no == 5:
        head = "## 第2巻\n\n" + head
    elif no == 1:
        head = "## 第1巻\n\n" + head
    return head + "\n\n" + "\n\n".join(chapter(n) for n in range(a, b + 1))


